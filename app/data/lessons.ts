const reflections: Lesson["reflectionPrompts"] = [
  "我今天能解释什么？",
  "我还不懂什么？",
  "今天如何应用？",
];

function makeLesson(input: Omit<Lesson, "schedule" | "reflectionPrompts" | "duration" | "difficulty"> & Partial<Pick<Lesson, "duration" | "difficulty">>): Lesson {
  return {
    ...input,
    duration: input.duration ?? 75,
    difficulty: input.difficulty ?? "零基础",
    schedule,
    reflectionPrompts: reflections,
  };
}

